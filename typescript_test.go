func TestTypeScriptGenerator_ModelsAndEndpoints(t *testing.T) {
	type EmbeddedMeta struct {
		CreatedAt time.Time `json:"createdAt"`
	}

	type CreateItemRequest struct {
		_ struct{} `doc:"Payload for creating a catalog item."`
		EmbeddedMeta
		Category    string                `param:"category" validate:"required"`
		DryRun      bool                  `query:"dry_run"`
		TraceID     string                `header:"X-Trace-ID"`
		Title       string                `json:"title" doc:"Item title" example:"Clean Code" validate:"required"`
		Priority    string                `json:"priority" default:"normal" validate:"omitempty,oneof=low normal high"`
		HyphenField bool                  `json:"is-featured"`
		Hidden      string                `json:"-"`
		Attachment  *multipart.FileHeader `form:"-"`
	}

	type ItemResponse struct {
		ID          string  `json:"id" example:"item_1"`
		Title       string  `json:"title"`
		Description *string `json:"description"`
		Priority    string  `json:"priority" validate:"oneof=low normal high"`
	}

	type UploadFormRequest struct {
		Avatar *multipart.FileHeader `form:"avatar" validate:"required"`
		Label  string                `form:"label"`
	}

	type UploadResponse struct {
		URL string `json:"url"`
	}

	app := repr.New(repr.Config{
		Title:       "Catalog API",
		Version:     "2.0.0",
		Description: "Catalog endpoints",
	})

	repr.Get(app, "/health", func(_ *repr.Context, _ repr.Empty) (repr.Empty, error) {
		return repr.Empty{}, nil
	}).Summary("Health check")

	repr.Post(app, "/categories/{category}/items", func(_ *repr.Context, _ CreateItemRequest) (ItemResponse, error) {
		return ItemResponse{}, nil
	}).Status(http.StatusCreated).
		Summary("Create item").
		ErrorResponse(http.StatusConflict, "Already exists")

	repr.Post(app, "/upload", func(_ *repr.Context, _ UploadFormRequest) (UploadResponse, error) {
		return UploadResponse{}, nil
	}).Summary("Upload avatar")

	repr.Get(app, "/events", func(_ *repr.Context, _ repr.Empty) (repr.SSEStream, error) {
		ch := make(chan repr.SSEvent)
		close(ch)
		return repr.SSEStream{Events: ch}, nil
	}).Summary("Event stream")

	repr.Get(app, "/internal", func(_ *repr.Context, _ repr.Empty) (repr.Empty, error) {
		return repr.Empty{}, nil
	}).Hidden()

	dts := app.GenerateTypeScript()
	sdk := app.GenerateTypeScriptSDK()

	checks := []string{
		"Auto-generated by Gota Framework \U0001F4A7. Do not edit by hand.",
		"API: Catalog API (2.0.0)",
		"* Payload for creating a catalog item.",
		"title: string;",
		`priority?: "low" | "normal" | "high";`,
		`"is-featured"?: boolean;`,
		"createdAt?: string;",
		"description: string | null;",
		`priority: "low" | "normal" | "high";`,
		"avatar: File | Blob;",
		"export interface GotaEndpoints",
		`"GET /health":`,
		`"POST /categories/{category}/items":`,
		`params: { category: string };`,
		`headers?: { "X-Trace-ID"?: string };`,
		`body: CreateItemRequest;`,
		`"POST /upload":`,
		`body: FormData | UploadFormRequest;`,
		`"GET /events":`,
		`response: ReadableStream<string>;`,
		"export declare function createGotaClient",
		"export declare function isGotaHttpError",
	}
	for _, want := range checks {
		if !strings.Contains(dts, want) {
			t.Errorf("expected %q in generated .d.ts, got:\n%s", want, dts)
		}
	}

	if strings.Contains(dts, "Hidden") {
		t.Errorf("expected json:\"-\" field Hidden to be omitted from .d.ts")
	}
	if strings.Contains(dts, "/internal") {
		t.Errorf("expected Hidden() route to be omitted from .d.ts")
	}

	sdkChecks := []string{
		"export function createGotaClient",
		"export function isGotaHttpError",
		"export class GotaHttpError",
		"export const DEFAULT_RETRY_METHODS",
		`"POST /upload": "multipart"`,
	}
	for _, want := range sdkChecks {
		if !strings.Contains(sdk, want) {
			t.Errorf("expected %q in generated sdk.ts", want)
		}
	}
}

func TestTypeScript_ReservedNameCollision(t *testing.T) {
	type Promise struct {
		Value string `json:"value"`
	}

	app := repr.New(repr.Config{Title: "Collision API"})
	repr.Get(app, "/p", func(_ *repr.Context, _ repr.Empty) (Promise, error) {
		return Promise{}, nil
	})

	dts := app.GenerateTypeScript()
	if strings.Contains(dts, "export interface Promise {") {
		t.Errorf("generated schema shadowed reserved global Promise:\n%s", dts)
	}
	if !strings.Contains(dts, "export interface gota_test_Promise {") && !strings.Contains(dts, "export interface Promise_2 {") {
		t.Errorf("expected disambiguated Promise interface name in:\n%s", dts)
	}
}

func TestTypeScript_DeterminismAndOrderIndependence(t *testing.T) {
	type SharedModel struct {
		Name  string  `json:"name"`
		Bio   *string `json:"bio"`
		Token string  `json:"token,omitempty"`
	}

	makeApp1 := func() *repr.App {
		a := repr.New(repr.Config{Title: "Order"})
		repr.Post(a, "/input", func(_ *repr.Context, _ SharedModel) (repr.Empty, error) {
			return repr.Empty{}, nil
		})
		repr.Get(a, "/output", func(_ *repr.Context, _ repr.Empty) (SharedModel, error) {
			return SharedModel{}, nil
		})
		return a
	}

	makeApp2 := func() *repr.App {
		a := repr.New(repr.Config{Title: "Order"})
		repr.Get(a, "/output", func(_ *repr.Context, _ repr.Empty) (SharedModel, error) {
			return SharedModel{}, nil
		})
		repr.Post(a, "/input", func(_ *repr.Context, _ SharedModel) (repr.Empty, error) {
			return repr.Empty{}, nil
		})
		return a
	}

	sdk1 := makeApp1().GenerateTypeScriptSDK()
	sdk2 := makeApp2().GenerateTypeScriptSDK()

	if sdk1 != sdk2 {
		t.Errorf("expected deterministic registration-order-independent SDK output")
	}
	if !strings.Contains(sdk1, "bio?: string;") {
		t.Errorf("expected shared model to keep request optionality (bio?: string), got:\n%s", sdk1)
	}
}

func TestTypeScript_HTTPRoutesAndDocsMiddleware(t *testing.T) {
	// 1. Disabled by default
	defaultApp := repr.New(repr.Config{})
	for _, p := range []string{"/types.d.ts", "/sdk.ts"} {
		rec := httptest.NewRecorder()
		defaultApp.ServeHTTP(rec, httptest.NewRequest(http.MethodGet, p, nil))
		if rec.Code != http.StatusNotFound {
			t.Errorf("expected 404 for %s by default, got %d", p, rec.Code)
		}
	}

	// 2. Disabled with "-"
	minusApp := repr.New(repr.Config{
		TypeScriptURL:    "-",
		TypeScriptSDKURL: "-",
	})
	for _, p := range []string{"/types.d.ts", "/sdk.ts"} {
		rec := httptest.NewRecorder()
		minusApp.ServeHTTP(rec, httptest.NewRequest(http.MethodGet, p, nil))
		if rec.Code != http.StatusNotFound {
			t.Errorf("expected 404 for %s when '-', got %d", p, rec.Code)
		}
	}

	// 3. Enabled & protected by DocsMiddlewares, isolated from App.Use
	app := repr.New(repr.Config{
		TypeScriptURL:    "/types.d.ts",
		TypeScriptSDKURL: "/sdk.ts",
		DocsMiddlewares: []func(http.Handler) http.Handler{
			func(next http.Handler) http.Handler {
				return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
					if r.Header.Get("X-Docs-Key") != "secret" {
						http.Error(w, "Unauthorized", http.StatusUnauthorized)
						return
					}
					next.ServeHTTP(w, r)
				})
			},
		},
	})
	app.Use(func(next http.Handler) http.Handler {
		return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			w.Header().Set("X-Global-MW", "true")
			next.ServeHTTP(w, r)
		})
	})

	repr.Get(app, "/ping", func(_ *repr.Context, _ repr.Empty) (map[string]string, error) {
		return map[string]string{"ok": "1"}, nil
	})

	for _, p := range []string{"/types.d.ts", "/sdk.ts"} {
		// Unauthenticated -> 401
		unauthRec := httptest.NewRecorder()
		app.ServeHTTP(unauthRec, httptest.NewRequest(http.MethodGet, p, nil))
		if unauthRec.Code != http.StatusUnauthorized {
			t.Errorf("expected 401 on unauthenticated %s, got %d", p, unauthRec.Code)
		}

		// Authenticated -> 200 with security headers and without global middleware
		req := httptest.NewRequest(http.MethodGet, p, nil)
		req.Header.Set("X-Docs-Key", "secret")
		rec := httptest.NewRecorder()
		app.ServeHTTP(rec, req)
		if rec.Code != http.StatusOK {
			t.Fatalf("expected 200 for %s, got %d", p, rec.Code)
		}
		if ct := rec.Header().Get("Content-Type"); !strings.Contains(ct, "application/typescript") {
			t.Errorf("expected application/typescript Content-Type on %s, got %q", p, ct)
		}
		if rec.Header().Get("X-Content-Type-Options") != "nosniff" {
			t.Errorf("expected X-Content-Type-Options: nosniff on %s", p)
		}
		if rec.Header().Get("Cache-Control") != "no-store" {
			t.Errorf("expected Cache-Control: no-store on %s", p)
		}
		if rec.Header().Get("X-Global-MW") != "" {
			t.Errorf("expected docs route %s to be isolated from global App.Use middleware", p)
		}
	}
}

func TestTypeScript_ExportAndRunCodegen(t *testing.T) {
	app := repr.New(repr.Config{Title: "Export API"})
	repr.Get(app, "/ping", func(_ *repr.Context, _ repr.Empty) (string, error) {
		return "pong", nil
	})

	tmpDir := t.TempDir()
	sdkOut := filepath.Join(tmpDir, "nested", "sdk.ts")
	dtsOut := filepath.Join(tmpDir, "nested", "types.d.ts")

	handled, err := app.RunCodegen([]string{"--ts-sdk=" + sdkOut, "--ts-types=" + dtsOut})
	if !handled || err != nil {
		t.Fatalf("RunCodegen failed: handled=%v err=%v", handled, err)
	}

	sdkBytes, err := os.ReadFile(sdkOut)
	if err != nil || !strings.Contains(string(sdkBytes), "createGotaClient") {
		t.Fatalf("failed reading exported sdk.ts: err=%v", err)
	}
	dtsBytes, err := os.ReadFile(dtsOut)
	if err != nil || !strings.Contains(string(dtsBytes), "GotaEndpoints") {
		t.Fatalf("failed reading exported types.d.ts: err=%v", err)
	}

	handled, err = app.RunCodegen([]string{"--port=8080"})
	if handled || err != nil {
		t.Errorf("expected unrelated flags to return handled=false, err=nil; got handled=%v err=%v", handled, err)
	}
}

func TestAuditRoutes(t *testing.T) {
	type LeakyRes struct {
		ID           string `json:"id"`
		PasswordHash string `json:"passwordHash"`
	}
	type CleanRes struct {
		ID           string `json:"id"`
		PasswordHash string `json:"-"`
	}

	app := repr.New(repr.Config{SilenceTagWarnings: true})
	repr.Get(app, "/leaky", func(_ *repr.Context, _ repr.Empty) (LeakyRes, error) {
		return LeakyRes{}, nil
	})
	repr.Get(app, "/clean", func(_ *repr.Context, _ repr.Empty) (CleanRes, error) {
		return CleanRes{}, nil
	})

	warnings := app.AuditRoutes()
	if len(warnings) != 1 {
		t.Fatalf("expected 1 AuditRoutes warning, got %d: %v", len(warnings), warnings)
	}
	if !strings.Contains(warnings[0], "/leaky") || !strings.Contains(warnings[0], "PasswordHash") {
		t.Errorf("unexpected AuditRoutes warning: %q", warnings[0])
	}
}

func TestTypeScript_NodeRuntimeE2E(t *testing.T) {
	nodePath, err := exec.LookPath("node")
	if err != nil {
		t.Skip("node not found on PATH; skipping Node E2E SDK execution")
	}

	type ItemReq struct {
		ID string `param:"id" validate:"required"`
	}
	type CreateReq struct {
		Title string `json:"title" validate:"required,min=3"`
	}
	type Item struct {
		ID    string `json:"id"`
		Title string `json:"title"`
	}

	app := repr.New(repr.Config{Title: "E2E API"})
	repr.Get(app, "/items/{id}", func(_ *repr.Context, req ItemReq) (Item, error) {
		if req.ID == "missing" {
			return Item{}, repr.NotFound("Item not found")
		}
		return Item{ID: req.ID, Title: "Found"}, nil
	}).ErrorResponse(http.StatusNotFound, "Not found")

	repr.Post(app, "/items", func(_ *repr.Context, req CreateReq) (Item, error) {
		return Item{ID: "new_1", Title: req.Title}, nil
	}).Status(http.StatusCreated)

	type NumericReq struct {
		ID string `param:"id" validate:"required"`
	}
	repr.Get(app, "/users/{id:[0-9]+}", func(_ *repr.Context, req NumericReq) (Item, error) {
		return Item{ID: req.ID, Title: "User"}, nil
	})

	srv := httptest.NewServer(app)
	defer srv.Close()

	tmpDir := t.TempDir()
	sdkPath := filepath.Join(tmpDir, "sdk.ts")
	if err := app.ExportTypeScriptSDK(sdkPath); err != nil {
		t.Fatalf("ExportTypeScriptSDK failed: %v", err)
	}

	sdkBytes, err := os.ReadFile(sdkPath)
	if err != nil {
		t.Fatalf("failed reading sdk.ts: %v", err)
	}
	if strings.Contains(string(sdkBytes), `kind !== ":"`) || strings.Contains(string(sdkBytes), `segment === "*"`) {
		t.Errorf("sdk.ts resolvePath should use only idiomatic Chi {param} syntax")
	}

	runnerScript := `
import assert from "node:assert/strict";
import { createGotaClient, isGotaHttpError } from "./sdk.ts";

const baseUrl = process.env.BASE_URL;
const api = createGotaClient(baseUrl);

// 1. GET with {id} path param
const item = await api.fetch("GET /items/{id}", { params: { id: "abc 123" } });
assert.equal(item.id, "abc 123");
assert.equal(item.title, "Found");

// 2. GET with {id:regex} Chi path param
const user = await api.fetch("GET /users/{id:[0-9]+}", { params: { id: "42" } });
assert.equal(user.id, "42");

// 3. POST with body
const created = await api.fetch("POST /items", { body: { title: "Hello World" } });
assert.equal(created.id, "new_1");
assert.equal(created.title, "Hello World");

// 4. 404 error narrowing
await assert.rejects(
  () => api.fetch("GET /items/{id}", { params: { id: "missing" } }),
  (err) => isGotaHttpError(err) && err.status === 404 && err.message === "Item not found"
);

// 5. 422 validation error narrowing
await assert.rejects(
  () => api.fetch("POST /items", { body: { title: "ab" } }),
  (err) => isGotaHttpError(err) && err.status === 422 && err.message === "Validation failed"
);
`
	runnerPath := filepath.Join(tmpDir, "run.mjs")
	if err := os.WriteFile(runnerPath, []byte(runnerScript), 0o644); err != nil {
		t.Fatalf("failed writing run.mjs: %v", err)
	}

	cmd := exec.Command(nodePath, runnerPath)
	cmd.Dir = tmpDir
	cmd.Env = append(os.Environ(), "BASE_URL="+srv.URL)
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("node E2E SDK test failed (node=%s): %v\n%s", nodePath, err, string(out))
	}
}
