	app.Post("/users", func(ctx *Context) error {
		return ctx.Json(TestUserRes{ID: "usr_1"})
	}).
		Summary("Create user").
		Description("Registers a new user into the database.").
		Body(TestCreateUserReq{}, "User creation payload").
		Response(http.StatusCreated, TestUserRes{}, "Created user")

	// Register GET /users/:id
	app.Get("/users/:id", func(ctx *Context) error {
		return ctx.Json(TestUserRes{ID: "usr_1"})
	}).
		Summary("Get user by ID").
		Param("id", "", "User unique ID").
		Query("verbose", false, "Include detailed fields").
		Response(http.StatusOK, TestUserRes{}, "User details")

	// Register DELETE /users/:id (No content 204)
	app.Delete("/users/:id", func(ctx *Context) error {
		return ctx.NoContent()
	}).
		Summary("Delete user").
		Param("id", "", "User ID to delete").
		Response(http.StatusNoContent, nil, "Deleted")

