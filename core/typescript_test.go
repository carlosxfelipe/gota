func TestTypeScriptGenerator_BasicAndModels(t *testing.T) {
	app := New(Config{
		Title:       "Sample API",
		Version:     "2.0.0",
		Description: "A test API for TypeScript generation.",
	})

	// Register POST /users
	app.Post("/users", func(ctx *Context) error {
		return ctx.Json(TestUserRes{ID: "usr_1"})
	}).
		Summary("Create user").
		Description("Registers a new user into the database.").
		Body(TestCreateUserReq{}, "User creation payload").
		Response(http.StatusCreated, TestUserRes{}, "Created user")

	// Register GET /users/:id
	app.Get("/users/:id", func(ctx *Context) error {
		return ctx.Json(TestUserRes{ID: "usr_1"})
	}).
		Summary("Get user by ID").
		Param("id", "", "User unique ID").
		Query("verbose", false, "Include detailed fields").
		Response(http.StatusOK, TestUserRes{}, "User details")

	// Register DELETE /users/:id (No content 204)
	app.Delete("/users/:id", func(ctx *Context) error {
		return ctx.NoContent()
	}).
		Summary("Delete user").
		Param("id", "", "User ID to delete").
		Response(http.StatusNoContent, nil, "Deleted")

	ts := app.GenerateTypeScript()

	// Verify Header
	if !strings.Contains(ts, "Auto-generated by Gota Framework") {
		t.Errorf("expected header, got:\n%s", ts)
	}
	if !strings.Contains(ts, "Sample API (2.0.0)") {
		t.Errorf("expected title and version, got:\n%s", ts)
	}

	// Verify Models
	if !strings.Contains(ts, "export interface TestCreateUserReq {") {
		t.Errorf("expected TestCreateUserReq interface, got:\n%s", ts)
	}
	if !strings.Contains(ts, `role: "Admin" | "Customer" | "Guest";`) {
		t.Errorf("expected oneof union type for role, got:\n%s", ts)
	}
	if !strings.Contains(ts, `status?: "active" | "inactive";`) {
		t.Errorf("expected optional oneof union type for status, got:\n%s", ts)
	}
	if !strings.Contains(ts, "name: string;") {
		t.Errorf("expected required name: string, got:\n%s", ts)
	}
	if !strings.Contains(ts, "age?: number;") {
		t.Errorf("expected optional age?: number, got:\n%s", ts)
	}
	if !strings.Contains(ts, "tags?: string[];") {
		t.Errorf("expected tags?: string[], got:\n%s", ts)
	}
	if !strings.Contains(ts, "payload?: string;") {
		t.Errorf("expected byte payload to be string (base64), got:\n%s", ts)
	}

	// Verify Embedded struct promotion
	if !strings.Contains(ts, "created_at?: string;") {
		t.Errorf("expected embedded created_at?: string, got:\n%s", ts)
	}

	// Verify JSDoc annotations
	if !strings.Contains(ts, "* User full name") {
		t.Errorf("expected doc comment, got:\n%s", ts)
	}
	if !strings.Contains(ts, "* @example Carlos") {
		t.Errorf("expected example annotation, got:\n%s", ts)
	}

	// Verify Endpoint Map
	if !strings.Contains(ts, `"POST /users": {`) {
		t.Errorf("expected POST /users in GotaEndpoints, got:\n%s", ts)
	}
	if !strings.Contains(ts, "body: TestCreateUserReq;") {
		t.Errorf("expected body: TestCreateUserReq, got:\n%s", ts)
	}
	if !strings.Contains(ts, "response: TestUserRes;") {
		t.Errorf("expected response: TestUserRes, got:\n%s", ts)
	}

	// Verify GET /users/:id with params and query
	if !strings.Contains(ts, `"GET /users/:id": {`) {
		t.Errorf("expected GET /users/:id in GotaEndpoints, got:\n%s", ts)
	}
	if !strings.Contains(ts, "params: { id: string };") {
		t.Errorf("expected params: { id: string }, got:\n%s", ts)
	}
	if !strings.Contains(ts, "query: { verbose?: boolean };") {
		t.Errorf("expected query: { verbose?: boolean }, got:\n%s", ts)
	}

	// Verify DELETE 204 response
	if !strings.Contains(ts, `"DELETE /users/:id": {`) {
		t.Errorf("expected DELETE /users/:id in GotaEndpoints, got:\n%s", ts)
	}
	if !strings.Contains(ts, "response: void;") {
		t.Errorf("expected response: void for 204 endpoint, got:\n%s", ts)
	}

	// Verify declare function createGotaClient in .d.ts
	if !strings.Contains(ts, "export declare function createGotaClient(baseUrl?: string): GotaClient;") {
		t.Errorf("expected declare function createGotaClient, got:\n%s", ts)
	}
}

