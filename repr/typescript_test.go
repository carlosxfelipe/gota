func TestTypeScript_NodeRuntimeE2E(t *testing.T) {
	nodePath, err := exec.LookPath("node")
	if err != nil {
		t.Skip("node not found on PATH; skipping Node E2E SDK execution")
	}

	type ItemReq struct {
		ID string `param:"id" validate:"required"`
	}
	type CreateReq struct {
		Title string `json:"title" validate:"required,min=3"`
	}
	type Item struct {
		ID    string `json:"id"`
		Title string `json:"title"`
	}

	app := repr.New(repr.Config{Title: "E2E API"})
	repr.Get(app, "/items/{id}", func(_ *repr.Context, req ItemReq) (Item, error) {
		if req.ID == "missing" {
			return Item{}, repr.NotFound("Item not found")
		}
		return Item{ID: req.ID, Title: "Found"}, nil
	}).ErrorResponse(http.StatusNotFound, "Not found")

	repr.Post(app, "/items", func(_ *repr.Context, req CreateReq) (Item, error) {
		return Item{ID: "new_1", Title: req.Title}, nil
	}).Status(http.StatusCreated)

	type NumericReq struct {
		ID string `param:"id" validate:"required"`
	}
	repr.Get(app, "/users/{id:[0-9]+}", func(_ *repr.Context, req NumericReq) (Item, error) {
		return Item{ID: req.ID, Title: "User"}, nil
	})

	repr.Get(app, "/slow", func(ctx *repr.Context, _ repr.Empty) (Item, error) {
		select {
		case <-time.After(2 * time.Second):
			return Item{ID: "slow", Title: "Done"}, nil
		case <-ctx.Request.Context().Done():
			return Item{}, ctx.Request.Context().Err()
		}
	})

	srv := httptest.NewServer(app)
	defer srv.Close()

	tmpDir := t.TempDir()
	sdkDir := filepath.Join(tmpDir, "sdk")
	if err := app.ExportTypeScriptSDK(sdkDir, repr.TypeScriptSDKOptions{ImportExtension: ".ts"}); err != nil {
		t.Fatalf("ExportTypeScriptSDK failed: %v", err)
	}

	runtimeBytes, err := os.ReadFile(filepath.Join(sdkDir, "runtime.ts"))
	if err != nil {
		t.Fatalf("failed reading runtime.ts: %v", err)
	}
	if strings.Contains(string(runtimeBytes), `kind !== ":"`) || strings.Contains(string(runtimeBytes), `segment === "*"`) {
		t.Errorf("runtime.ts resolvePath should use only idiomatic Chi {param} syntax")
	}

	runnerScript := `
import assert from "node:assert/strict";
import {
  createGotaClient,
  isAbortError,
  isEndpointError,
  isGotaHttpError,
  parseGotaError,
} from "./sdk/index.ts";
import { parseGotaError as parseRuntimeOnlyError } from "./sdk/runtime.ts";

const baseUrl = process.env.BASE_URL;
const api = createGotaClient(baseUrl);

// 1. GET with {id} path param
const item = await api.fetch("GET /items/{id}", { params: { id: "abc 123" } });
assert.equal(item.id, "abc 123");
assert.equal(item.title, "Found");

// 2. GET with {id:regex} Chi path param
const user = await api.fetch("GET /users/{id:[0-9]+}", { params: { id: "42" } });
assert.equal(user.id, "42");

// 3. POST with body
const created = await api.fetch("POST /items", { body: { title: "Hello World" } });
assert.equal(created.id, "new_1");
assert.equal(created.title, "Hello World");

// 4. 404 error narrowing & parseGotaError
await assert.rejects(
  () => api.fetch("GET /items/{id}", { params: { id: "missing" } }),
  (err) => {
    const parsed = parseGotaError(err);
    return (
      isGotaHttpError(err) &&
      isEndpointError(err, "GET /items/{id}") &&
      !isEndpointError(err, "POST /items") &&
      err.status === 404 &&
      err.message === "Item not found" &&
      parsed.kind === "http" &&
      parsed.status === 404 &&
      parsed.message === "Item not found" &&
      parsed.endpoint === "GET /items/{id}" &&
      Object.keys(parsed.fieldErrors).length === 0
    );
  }
);

// 5. 422 validation error narrowing & fieldErrors
await assert.rejects(
  () => api.fetch("POST /items", { body: { title: "ab" } }),
  (err) => {
    const parsed = parseGotaError(err);
    return (
      isGotaHttpError(err) &&
      err.status === 422 &&
      err.message === "Validation failed" &&
      parsed.kind === "validation" &&
      parsed.status === 422 &&
      Array.isArray(parsed.fieldErrors["title"]) &&
      parsed.fieldErrors["title"].length > 0
    );
  }
);

// 6. AbortController cancellation skips onError hook & is identified by isAbortError/parseGotaError
let onErrorCalled = 0;
const controller = new AbortController();
setTimeout(() => controller.abort(), 30);
await assert.rejects(
  () =>
    api.fetch("GET /slow", {
      signal: controller.signal,
      onError: () => {
        onErrorCalled++;
      },
    }),
  (err) => {
    const parsed = parseRuntimeOnlyError(err);
    return isAbortError(err) && parsed.kind === "abort";
  }
);
assert.equal(onErrorCalled, 0);

// 7. Timeout is distinguished from caller AbortController cancellation
await assert.rejects(
  () => api.fetch("GET /slow", { timeoutMs: 30 }),
  (err) => !isAbortError(err) && parseGotaError(err).kind === "timeout"
);

// 8. queryOptions builds stable queryKey and forwards signal to queryFn
const qOpts = api.queryOptions("GET /items/{id}", { params: { id: "q1" } });
assert.deepEqual(qOpts.queryKey, ["GET /items/{id}", { params: { id: "q1" } }]);
const qRes = await qOpts.queryFn();
assert.equal(qRes.id, "q1");

const qSlow = api.queryOptions("GET /slow");
const qController = new AbortController();
setTimeout(() => qController.abort(), 30);
await assert.rejects(
  () => qSlow.queryFn({ signal: qController.signal }),
  (err) => isAbortError(err)
);
`
	runnerPath := filepath.Join(tmpDir, "run.mjs")
	if err := os.WriteFile(runnerPath, []byte(runnerScript), 0o644); err != nil {
		t.Fatalf("failed writing run.mjs: %v", err)
	}

	cmd := exec.Command(nodePath, runnerPath)
	cmd.Dir = tmpDir
	cmd.Env = append(os.Environ(), "BASE_URL="+srv.URL)
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("node E2E SDK test failed (node=%s): %v\n%s", nodePath, err, string(out))
	}
}

func TestTypeScript_SDKFilesLayoutAndSharing(t *testing.T) {
	type SharedLeaf struct {
		Code string `json:"code"`
	}
	type SharedMeta struct {
		Leaf SharedLeaf `json:"leaf"`
	}
	type RecursiveNode struct {
		ID   string         `json:"id"`
		Next *RecursiveNode `json:"next,omitempty"`
	}
	type TodoItem struct {
		ID   string         `json:"id"`
		Meta SharedMeta     `json:"meta"`
		Node *RecursiveNode `json:"node,omitempty"`
	}
	// Intentionally collides with the generated module interface name for tag "Todos".
	type TodosEndpoints struct {
		Marker string `json:"marker"`
	}
	type ProfileRes struct {
		Meta SharedMeta `json:"meta"`
	}

	buildApp := func(reverse bool) *repr.App {
		a := repr.New(repr.Config{Title: "Modular API", Version: "1.0.0"})
		regTodos := func() {
			repr.Get(a, "/todos", func(_ *repr.Context, _ repr.Empty) ([]TodoItem, error) {
				return nil, nil
			}).Tags("Todos")
			repr.Post(a, "/todos/meta", func(_ *repr.Context, _ TodosEndpoints) (repr.Empty, error) {
				return repr.Empty{}, nil
			}).Tags("Todos")
		}
		regUsers := func() {
			repr.Get(a, "/profiles", func(_ *repr.Context, _ repr.Empty) (ProfileRes, error) {
				return ProfileRes{}, nil
			}).Tags("User Profiles")
		}
		regAccented := func() {
			repr.Get(a, "/usuarios", func(_ *repr.Context, _ repr.Empty) (repr.Empty, error) {
				return repr.Empty{}, nil
			}).Tags("Usuários")
		}
		regUntagged := func() {
			repr.Get(a, "/ping", func(_ *repr.Context, _ repr.Empty) (string, error) {
				return "pong", nil
			})
		}
		if reverse {
			regUntagged()
			regAccented()
			regUsers()
			regTodos()
		} else {
			regTodos()
			regUsers()
			regAccented()
			regUntagged()
		}
		return a
	}

	files1, err := buildApp(false).GenerateTypeScriptSDK()
	if err != nil {
		t.Fatalf("GenerateTypeScriptSDK failed: %v", err)
	}
	files2, err := buildApp(true).GenerateTypeScriptSDK()
	if err != nil {
		t.Fatalf("GenerateTypeScriptSDK(reverse) failed: %v", err)
	}
	if !maps.Equal(files1, files2) {
		t.Fatalf("expected deterministic registration-order-independent SDK files")
	}

	expectedPaths := []string{
		"index.ts",
		"runtime.ts",
		"types/_shared.ts",
		"types/todos.ts",
		"types/user-profiles.ts",
		"endpoints/default.ts",
		"endpoints/todos.ts",
		"endpoints/user-profiles.ts",
		"endpoints/usuarios.ts",
	}
	for _, p := range expectedPaths {
		if _, ok := files1[p]; !ok {
			t.Errorf("expected generated file %q, got keys: %v", p, keysOf(files1))
		}
	}

	// SharedMeta and its transitive dependency SharedLeaf must both live in _shared.ts.
	shared := files1["types/_shared.ts"]
	if !strings.Contains(shared, "export interface SharedMeta") || !strings.Contains(shared, "export interface SharedLeaf") {
		t.Errorf("expected SharedMeta and SharedLeaf in types/_shared.ts, got:\n%s", shared)
	}
	if strings.Contains(shared, "import ") {
		t.Errorf("types/_shared.ts must not import module files:\n%s", shared)
	}

	// TodoItem and RecursiveNode belong only to todos.ts, and RecursiveNode must not self-import.
	todosTypes := files1["types/todos.ts"]
	if !strings.Contains(todosTypes, "export interface TodoItem") || !strings.Contains(todosTypes, "export interface RecursiveNode") {
		t.Errorf("expected TodoItem and RecursiveNode in types/todos.ts, got:\n%s", todosTypes)
	}
	if !strings.Contains(todosTypes, `import type { SharedMeta } from "./_shared";`) {
		t.Errorf("expected types/todos.ts to import SharedMeta from ./_shared, got:\n%s", todosTypes)
	}
	if strings.Contains(todosTypes, `from "./todos"`) {
		t.Errorf("types/todos.ts must not self-import:\n%s", todosTypes)
	}

	// Struct named TodosEndpoints must be disambiguated so it doesn't collide with TodosEndpoints module interface.
	todosEP := files1["endpoints/todos.ts"]
	if !strings.Contains(todosEP, "export interface TodosEndpoints {") {
		t.Errorf("expected module interface TodosEndpoints in endpoints/todos.ts")
	}
	if strings.Contains(todosTypes, "export interface TodosEndpoints {") {
		t.Errorf("schema TodosEndpoints should have been disambiguated:\n%s", todosTypes)
	}

	// Tree-shaking checks.
	if !strings.Contains(files1["runtime.ts"], "/* @__PURE__ */") {
		t.Errorf("expected /* @__PURE__ */ annotation in runtime.ts for tree-shaking")
	}
	if !strings.Contains(files1["index.ts"], `export type * from "./types/todos";`) {
		t.Errorf("expected export type * in index.ts")
	}

	// ImportExtension validation and support.
	if _, err := buildApp(false).GenerateTypeScriptSDK(repr.TypeScriptSDKOptions{ImportExtension: ".mjs"}); err == nil {
		t.Errorf("expected error for unsupported ImportExtension")
	}
	jsFiles, err := buildApp(false).GenerateTypeScriptSDK(repr.TypeScriptSDKOptions{ImportExtension: ".js"})
	if err != nil {
		t.Fatalf("GenerateTypeScriptSDK(.js) failed: %v", err)
	}
	if !strings.Contains(jsFiles["index.ts"], `from "./runtime.js"`) ||
		!strings.Contains(jsFiles["endpoints/todos.ts"], `from "../types/todos.js"`) {
		t.Errorf("expected .js import specifiers when ImportExtension is .js")
	}
}

func TestTypeScript_ExportDirStaleCleanupAndCheck(t *testing.T) {
	type Item struct {
		ID string `json:"id"`
	}

	app := repr.New(repr.Config{Title: "Check API"})
	repr.Get(app, "/items", func(_ *repr.Context, _ repr.Empty) ([]Item, error) {
		return nil, nil
	}).Tags("Items")

	tmpDir := t.TempDir()
	sdkDir := filepath.Join(tmpDir, "sdk")
	dtsFile := filepath.Join(tmpDir, "types.d.ts")

	// Export everything via RunCodegen.
	handled, err := app.RunCodegen([]string{
		"--ts-sdk=" + sdkDir,
		"--ts-types=" + dtsFile,
	})
	if !handled || err != nil {
		t.Fatalf("RunCodegen export failed: handled=%v err=%v", handled, err)
	}

	// --check should succeed right after export.
	if handled, err := app.RunCodegen([]string{
		"--ts-sdk=" + sdkDir,
		"--ts-types=" + dtsFile,
		"--check",
	}); !handled || err != nil {
		t.Fatalf("RunCodegen --check failed: handled=%v err=%v", handled, err)
	}

	// Write both a user-owned file (no markers) and a stale Gota-managed file inside sdkDir.
	customFile := filepath.Join(sdkDir, "custom.ts")
	if err := os.WriteFile(customFile, []byte("export const myHelper = 1;\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	staleFile := filepath.Join(sdkDir, "endpoints", "legacy.ts")
	staleContent := "/**\n * Auto-generated by Gota Framework \U0001F4A7. Do not edit by hand.\n * This directory is managed by Gota codegen\n */\nexport interface LegacyEndpoints {}\n"
	if err := os.WriteFile(staleFile, []byte(staleContent), 0o644); err != nil {
		t.Fatal(err)
	}

	// Modify index.ts so --check detects both changed and stale files.
	indexPath := filepath.Join(sdkDir, "index.ts")
	if err := os.WriteFile(indexPath, []byte("// dirty\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	if err := app.CheckTypeScriptSDK(sdkDir); err == nil ||
		!strings.Contains(err.Error(), "changed [index.ts]") ||
		!strings.Contains(err.Error(), "stale [endpoints/legacy.ts]") {
		t.Fatalf("expected CheckTypeScriptSDK to report changed index.ts and stale endpoints/legacy.ts, got: %v", err)
	}

	// Re-exporting should remove staleFile, restore index.ts, and preserve custom.ts.
	if err := app.ExportTypeScriptSDK(sdkDir); err != nil {
		t.Fatalf("ExportTypeScriptSDK failed: %v", err)
	}
	if _, err := os.Stat(staleFile); !os.IsNotExist(err) {
		t.Errorf("expected stale managed file %s to be deleted, stat err=%v", staleFile, err)
	}
	if _, err := os.Stat(customFile); err != nil {
		t.Errorf("expected user file %s to be preserved, stat err=%v", customFile, err)
	}
	if err := app.CheckTypeScriptSDK(sdkDir); err != nil {
		t.Errorf("expected CheckTypeScriptSDK to pass after re-export, got: %v", err)
	}

	// Invalid --check flag combinations.
	if handled, err := app.RunCodegen([]string{"--check"}); !handled || err == nil {
		t.Errorf("expected --check without target to return handled=true and error")
	}
	if handled, err := app.RunCodegen([]string{"--stdout", "--check"}); !handled || err == nil {
		t.Errorf("expected --stdout --check to return handled=true and error")
	}
	if handled, err := app.RunCodegen([]string{"--ts-import-ext=.bad"}); !handled || err == nil {
		t.Errorf("expected invalid --ts-import-ext to return handled=true and error")
	}
}

func keysOf(m map[string]string) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	return out
}
