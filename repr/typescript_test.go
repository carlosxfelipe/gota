func TestTypeScript_DeterminismAndOrderIndependence(t *testing.T) {
	type SharedModel struct {
		Name  string  `json:"name"`
		Bio   *string `json:"bio"`
		Token string  `json:"token,omitempty"`
	}

	makeApp1 := func() *repr.App {
		a := repr.New(repr.Config{Title: "Order"})
		repr.Post(a, "/input", func(_ *repr.Context, _ SharedModel) (repr.Empty, error) {
			return repr.Empty{}, nil
		})
		repr.Get(a, "/output", func(_ *repr.Context, _ repr.Empty) (SharedModel, error) {
			return SharedModel{}, nil
		})
		return a
	}

	makeApp2 := func() *repr.App {
		a := repr.New(repr.Config{Title: "Order"})
		repr.Get(a, "/output", func(_ *repr.Context, _ repr.Empty) (SharedModel, error) {
			return SharedModel{}, nil
		})
		repr.Post(a, "/input", func(_ *repr.Context, _ SharedModel) (repr.Empty, error) {
			return repr.Empty{}, nil
		})
		return a
	}

	sdk1, err := makeApp1().GenerateTypeScriptSDK()
	if err != nil {
		t.Fatalf("GenerateTypeScriptSDK(1) failed: %v", err)
	}
	sdk2, err := makeApp2().GenerateTypeScriptSDK()
	if err != nil {
		t.Fatalf("GenerateTypeScriptSDK(2) failed: %v", err)
	}

	if !maps.Equal(sdk1, sdk2) {
		t.Errorf("expected deterministic registration-order-independent SDK output")
	}
	sharedTypes := sdk1["types/_shared.ts"]
	if !strings.Contains(sharedTypes, "bio?: string;") {
		t.Errorf("expected shared model to keep request optionality (bio?: string), got:\n%s", sharedTypes)
	}
}

func TestTypeScript_ExportAndRunCodegen(t *testing.T) {
	app := repr.New(repr.Config{Title: "Export API"})
	repr.Get(app, "/ping", func(_ *repr.Context, _ repr.Empty) (string, error) {
		return "pong", nil
	})

	tmpDir := t.TempDir()
	sdkOut := filepath.Join(tmpDir, "nested", "sdk")

	handled, err := app.RunCodegen([]string{"--ts-sdk=" + sdkOut})
	if !handled || err != nil {
		t.Fatalf("RunCodegen failed: handled=%v err=%v", handled, err)
	}

	indexBytes, err := os.ReadFile(filepath.Join(sdkOut, "index.ts"))
	if err != nil || !strings.Contains(string(indexBytes), "createGotaClient") {
		t.Fatalf("failed reading exported sdk/index.ts: err=%v", err)
	}
	runtimeBytes, err := os.ReadFile(filepath.Join(sdkOut, "runtime.ts"))
	if err != nil || !strings.Contains(string(runtimeBytes), "createGotaClientFor") {
		t.Fatalf("failed reading exported sdk/runtime.ts: err=%v", err)
	}

	handled, err = app.RunCodegen([]string{"--port=8080"})
	if handled || err != nil {
		t.Errorf("expected unrelated flags to return handled=false, err=nil; got handled=%v err=%v", handled, err)
	}
}

